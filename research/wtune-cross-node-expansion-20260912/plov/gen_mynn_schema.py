#!/usr/bin/env python3
"""Generate the locked MYNN source-metadata header, never a native ABI claim."""
import argparse
import hashlib
import json
from pathlib import Path
import re

SCHEMA_SHA256 = '73225add0c60a4c5ac0da76a67d913a89fd7ad7e641f3cfdc01079ae0724133b'
CONDITIONS = ['NEVER', 'ALWAYS', 'PRESENT', 'QC', 'QI', 'QS', 'QNC', 'QNI',
              'QNWFA', 'QNIFA', 'QNBCA', 'PLUME', 'OUTPUT', 'SPP', 'BUDGET']
SPECIES = {'qc', 'qi', 'qs', 'qnc', 'qni', 'qnwfa', 'qnifa', 'qnbca'}


def condition(text, name):
    fixed = {'none': 'NEVER', 'always': 'ALWAYS',
             'always;read_if(initflag==0.or.restart)': 'ALWAYS',
             'bl_mynn_edmf>0': 'PLUME', 'bl_mynn_output>0': 'OUTPUT',
             'spp_pbl>0': 'SPP', 'tke_budget==1': 'BUDGET'}
    if text in fixed:
        return 'WT_MYNN_COND_' + fixed[text]
    if text == 'present(' + name + ')':
        return 'WT_MYNN_COND_PRESENT'
    if name in SPECIES and text == 'flag_' + name:
        return 'WT_MYNN_COND_' + name.upper()
    raise ValueError('unknown branch condition: ' + text)


def generate(raw):
    if hashlib.sha256(raw).hexdigest() != SCHEMA_SHA256:
        raise ValueError('schema SHA-256 mismatch; refreshed schema requires review')
    schema = json.loads(raw)
    args = schema['arguments']
    if schema['argument_count'] != 132 or schema['index_base'] != 0 or len(args) != 132:
        raise ValueError('unsupported formal count/index profile')
    lines = ['/* Generated by gen_mynn_schema.py; do not hand-edit.',
             ' * Source metadata only. Four-byte layout requires independent native ABI proof. */',
             '#ifndef WT_MYNN_SCHEMA_H', '#define WT_MYNN_SCHEMA_H',
             '#define WT_MYNN_SCHEMA_SHA256 "' + SCHEMA_SHA256 + '"',
             '#define WT_MYNN_NARG 132',
             'enum wt_mynn_type { WT_MYNN_REAL, WT_MYNN_INTEGER, WT_MYNN_LOGICAL };',
             'enum wt_mynn_intent { WT_MYNN_IN, WT_MYNN_INOUT, WT_MYNN_OUT };',
             'enum wt_mynn_condition {']
    lines += ['    WT_MYNN_COND_' + name + ',' for name in CONDITIONS]
    lines += ['};', 'enum wt_mynn_argument {']
    seen = set()
    for i, arg in enumerate(args):
        name = arg['name']
        if arg['index'] != i or name in seen or not re.fullmatch('[a-z][a-z0-9_]*', name):
            raise ValueError('invalid ordered formal identity')
        seen.add(name)
        rank = arg['rank']
        shape = {0: [], 2: ['ims:ime', 'jms:jme'],
                 3: ['ims:ime', 'kms:kme', 'jms:jme']}.get(rank)
        if shape is None or arg['shape'] != shape or arg['byte_width'] is not None:
            raise ValueError('unsupported shape or unverified width')
        if arg['kind'] != ('kind_phys' if arg['type'] == 'real' else 'default'):
            raise ValueError('unsupported kind')
        if rank == 0 and (arg['intent'] != 'in' or arg['optional']):
            raise ValueError('scalar must be required/read-only')
        lines.append('    WT_MYNN_' + name.upper() + ' = ' + str(i) + ',')
    lines += ['};', 'struct wt_mynn_arg_metadata {',
              '    const char *name;',
              '    unsigned char type, rank, optional, intent, access, write;',
              '};',
              '/* Shape by rank: 0 scalar; 2 (ims:ime,jms:jme);',
              ' * 3 (ims:ime,kms:kme,jms:jme), in Fortran storage order. */',
              'static const struct wt_mynn_arg_metadata wt_mynn_args[WT_MYNN_NARG] = {']
    for arg in args:
        values = ['"' + arg['name'] + '"', 'WT_MYNN_' + arg['type'].upper(),
                  str(arg['rank']), str(int(arg['optional'])), 'WT_MYNN_' + arg['intent'].upper(),
                  condition(arg['access_condition'], arg['name']), condition(arg['write_condition'], arg['name'])]
        lines.append('    {' + ', '.join(values) + '},')
    lines += ['};', '#endif', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--schema', type=Path, default=Path(__file__).with_name('mynn_schema.json'))
    parser.add_argument('--output', type=Path, default=Path(__file__).with_name('wt_mynn_schema.h'))
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    try:
        header = generate(args.schema.read_bytes())
        if args.check:
            if args.output.read_text() != header:
                raise ValueError('generated header mismatch')
        else:
            args.output.write_text(header)
    except (ValueError, KeyError, OSError) as error:
        parser.exit(1, str(error) + '\n')


if __name__ == '__main__':
    main()
