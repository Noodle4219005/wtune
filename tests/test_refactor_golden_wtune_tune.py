"""Characterization (golden) tests for wtune.tune.run / run_pipeline_full, pinned BEFORE the
readability refactor that split both into phase helpers.

Two kinds of snapshot, both generated by the unchanged code and stored under
tests/fixtures/golden/wtune/tune/:

  pipeline_<name>.txt / .json  the full printed text and the tune_report.json bytes of a fake
                               pipeline run (the _pipe_run fakes of test_wtune_tune.py), one per
                               representative path: -O0..-O3, degraded / skipped / aborted phase 2,
                               budget truncation, step-down, the t0-anchor prediction, ...
  dispatch.json                for a list of argv, what run() hands to the selected runner
                               (run_level0 / run_pipeline_full / run_node_search /
                               run_tuning_at, all replaced by recorders): its kwargs and every
                               non-callable Ctx attribute -- pins argument resolution, the context
                               build and the dispatch table without running any search.

The temporary directory is replaced by <TMP>, the wall-clock probe time of the node pre-flight by
<PROBE_S>. wtune.advise is replaced by a stub (its output is not wtune.tune's to pin).

Regenerate (only with the UNCHANGED code): WTUNE_GOLDEN_REGEN=1 pytest tests/<this file>.
"""
