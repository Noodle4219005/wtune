#!/usr/bin/env python3
"""Generate the locked GNU --wrap reference bridge for MYNN's outer driver.

This generator deliberately understands only the frozen, pointer-only MYNN
driver interface.  It is not an ABI attestation: the generated C wrapper
preserves the compiler-provided pointer arguments and reports that native ABI
proof has not yet been established.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

from gen_phase_schema import SchemaError, extract, write_atomic


SCHEMA_SHA256 = "73225add0c60a4c5ac0da76a67d913a89fd7ad7e641f3cfdc01079ae0724133b"
SOURCE_SHA256 = "9b339c1bb9e318086113b99e40f691d731639adbe57b579cf98046bf3f2dcfde"
SOURCE_KEY = "phys/module_bl_mynnedmf_driver.f90"
PROCEDURE = "mynnedmf_driver"
SYMBOL = "module_bl_mynnedmf_driver_mp_mynnedmf_driver_"
NARGS = 132
IDENTIFIER = re.compile(r"[A-Za-z_][A-Za-z0-9_]*\Z")


def checked_identifier(value):
    if not IDENTIFIER.fullmatch(value):
        raise SchemaError("symbol must be a C identifier")
    return value


def checked_schema(path):
    raw = Path(path).read_bytes()
    if hashlib.sha256(raw).hexdigest() != SCHEMA_SHA256:
        raise SchemaError("schema SHA-256 does not match the audited MYNN schema")
    schema = json.loads(raw)
    if (schema.get("phase") != "mynn" or schema.get("routine") != PROCEDURE or
            schema.get("argument_count") != NARGS or schema.get("index_base") != 0):
        raise SchemaError("schema has an unsupported MYNN interface declaration")
    if schema.get("source_sha256", {}).get(SOURCE_KEY) != SOURCE_SHA256:
        raise SchemaError("schema source SHA-256 does not match the audited MYNN driver")
    arguments = schema.get("arguments")
    if not isinstance(arguments, list) or len(arguments) != NARGS:
        raise SchemaError("schema must contain the ordered audited 132 arguments")
    for index, argument in enumerate(arguments):
        if (not isinstance(argument, dict) or argument.get("index") != index or
                not isinstance(argument.get("name"), str) or
                not re.fullmatch(r"[a-z][a-z0-9_]*", argument["name"])):
            raise SchemaError("schema has an unsupported ordered argument declaration")
    return schema


def checked_source(source, schema):
    """Validate structure before digest, so unsafe declaration failures are clear."""
    manifest = extract(str(source), PROCEDURE)
    arguments = manifest["arguments"]
    if len(arguments) != NARGS:
        raise SchemaError("MYNN source must declare exactly 132 arguments")
    expected_names = [argument["name"] for argument in schema["arguments"]]
    actual_names = [argument["name"] for argument in arguments]
    if actual_names != expected_names:
        raise SchemaError("MYNN source argument order differs from the audited schema")
    for expected, argument in zip(schema["arguments"], arguments):
        allowed = {"unresolved_kind"} if expected.get("kind") == "kind_phys" else {"missing_kind"}
        unsupported = set(argument["unsupported_reasons"]) - allowed
        if (unsupported or argument["type"] != expected.get("type") or
                argument["type"] not in {"real", "integer", "logical"}):
            details = ",".join(sorted(unsupported)) or str(argument["type"])
            raise SchemaError("unsupported MYNN ABI declaration for %s: %s" %
                              (argument["name"], details))
        if len(argument["dimensions"]) not in {0, 2, 3}:
            raise SchemaError("unsupported MYNN ABI rank for " + argument["name"])
    if manifest["source"]["sha256"] != SOURCE_SHA256:
        raise SchemaError("source SHA-256 does not match the audited MYNN driver")
    return arguments


def generate(source, schema_path, symbol=SYMBOL):
    schema = checked_schema(schema_path)
    arguments = checked_source(source, schema)
    symbol = checked_identifier(symbol)
    formals = ", ".join("void *a%d" % index for index in range(NARGS))
    argv = ", ".join("a%d" % index for index in range(NARGS))
    forwarded = ", ".join("args[%d]" % index for index in range(NARGS))
    optional = sum(1 for argument in schema["arguments"] if argument.get("optional"))
    return "\n".join((
        "/* Generated by gen_mynn_bridge.py; do not hand-edit.",
        " * source_sha256=%s schema_sha256=%s; %d arguments, %d optional." %
        (SOURCE_SHA256, SCHEMA_SHA256, NARGS, optional),
        " * Pointer forwarding is compiler-managed; native ABI attestation remains false. */",
        "#include <stddef.h>",
        "#define WT_MYNN_BRIDGE_NARG 132u",
        "extern void __real_%s(%s);" % (symbol, formals),
        "extern void wt_mynn_bridge_dispatch(void **, void (*)(void **), size_t)",
        "    __attribute__((weak));",
        "static void wt_mynn_bridge_real(void **args) {",
        "  __real_%s(%s);" % (symbol, forwarded),
        "}",
        "/* A linked dispatcher owns admission; absent one, invoke native once. */",
        "void __wrap_%s(%s) {" % (symbol, formals),
        "  void *args[WT_MYNN_BRIDGE_NARG] = {%s};" % argv,
        "  if (wt_mynn_bridge_dispatch != NULL)",
        "    wt_mynn_bridge_dispatch(args, wt_mynn_bridge_real, WT_MYNN_BRIDGE_NARG);",
        "  else wt_mynn_bridge_real(args);",
        "}",
        "",
    ))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", required=True)
    parser.add_argument("--schema", default=str(Path(__file__).with_name("mynn_schema.json")))
    parser.add_argument("--symbol", default=SYMBOL)
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    try:
        write_atomic(args.output, generate(args.source, args.schema, args.symbol))
    except (OSError, UnicodeDecodeError, json.JSONDecodeError, SchemaError) as error:
        parser.error(str(error))


if __name__ == "__main__":
    main()
