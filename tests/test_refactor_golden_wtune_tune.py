def _norm(text, tmp_path):
    text = text.replace(str(tmp_path), "<TMP>")
    text = text.replace(os.path.realpath(REPO), "<REPO>").replace(REPO, "<REPO>")
    text = text.replace(str(tmp_path.parent), "<BASETEMP>")    # conftest's history dir
    text = re.sub(r'"probe_s": [0-9.e-]+', '"probe_s": "<PROBE_S>"', text)
    text = re.sub(r"\(\d+\.\ds, controller time\)", "(<PROBE_S>, controller time)", text)
    text = re.sub(r"probe \d+\.\ds", "probe <PROBE_S>", text)
    return text


def _check(name, got):
    """Compare with the stored snapshot; a snapshot over 200 kB is stored as its sha256 only."""
    if len(got) > 200_000:
        name, got = name + ".sha256", hashlib.sha256(got.encode()).hexdigest() + "\n"
    path = os.path.join(GOLDEN, name)
    if REGEN:
        os.makedirs(GOLDEN, exist_ok=True)
        with open(path, "w") as f:
            f.write(got)
        return
    with open(path) as f:
        want = f.read()
    assert got == want, "golden mismatch: %s" % name


